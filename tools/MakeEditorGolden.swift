// Writes porting/golden/mermaid-editor.json: input → output pairs from MermaidSourceEditor, so the
// Rust port of the visual editor can be checked against the exact Swift behaviour.
// Build and run (from the project root):
//   swiftc -parse-as-library Renderooo/MermaidSourceEditor.swift tools/MakeEditorGolden.swift -o build/MakeEditorGolden
//   build/MakeEditorGolden
import Foundation

@main
enum MakeEditorGolden {
    static let sources: [String: String] = [
        "brackets": """
        flowchart LR
            A[Start] --> B{Choose?}
            B -->|yes| C(Rounded)
            B -->|no| D([Pill])
            C --> E[["Sub [x]"]]
            D --> F[(DB)]
            E --> G((Circle))
            F --> H{{Hex}}
            G --> I[/Lean/]
            H --> J>Flag]
            I --> K
            J --> K
            style C fill:#fde2e1,color:#1f2328,stroke:#333
        """,
        "expanded": """
        flowchart TD
            A@{ shape: rect, label: "Hello" } --> B@{ shape: diamond }
            B --> C@{ label: "Only label" }
        """,
        "subgraphs": """
        flowchart LR
            subgraph S1 [Section]
                A1[One<br/>two] --> A2["Say #quot;hi#quot;"]
            end
            A2 --> A10[Ten]
            class A1 done
        """,
        "crlf": "flowchart LR\r\n    A[One] --> B[Two]\r\n",
    ]

    struct Case: Encodable {
        var source: String
        var op: String
        var id: String
        var arg: String?
        var output: String
    }

    struct DetailsCase: Encodable {
        var source: String
        var id: String
        var label: String
        var shape: String?
        var fill: String?
    }

    static func main() throws {
        var files = sources
        let samples = URL(fileURLWithPath: "Samples")
        for name in ["Flow.mmd", "Workflow.mmd"] {
            if let text = try? String(contentsOf: samples.appendingPathComponent(name), encoding: .utf8) { files[name] = text }
        }

        let ids = ["A", "B", "C", "D", "E", "F", "G", "H", "I", "J", "K", "A1", "A2", "A10", "M", "Missing"]
        var edits: [Case] = []
        var details: [DetailsCase] = []
        for (name, source) in files.sorted(by: { $0.key < $1.key }) {
            for id in ids where source.contains(id) || id == "Missing" {
                let d = MermaidSourceEditor.details(of: id, in: source)
                details.append(.init(source: name, id: id, label: d.label, shape: d.shape?.rawValue, fill: d.fill))
                edits.append(.init(source: name, op: "setLabel", id: id, arg: "New \"label\"\nline 2",
                                   output: MermaidSourceEditor.setLabel("New \"label\"\nline 2", of: id, in: source)))
                for shape in [NodeShape.stadium, .cylinder, .flag] {
                    edits.append(.init(source: name, op: "setShape", id: id, arg: shape.rawValue,
                                       output: MermaidSourceEditor.setShape(shape, of: id, in: source)))
                }
                for fill in ["#0A2342", "#FFF8C5", nil] {
                    edits.append(.init(source: name, op: "setFill", id: id, arg: fill,
                                       output: MermaidSourceEditor.setFill(fill, of: id, in: source)))
                }
            }
        }
        let isDark = ["#000", "#fff", "#0A2342", "#F4D35E", "#3D6B5E", "#E07A5F", "#6B7280", "#808080"]
            .map { ["hex": $0, "dark": MermaidSourceEditor.isDark($0) ? "true" : "false"] }

        struct Golden: Encodable {
            var note: String
            var sources: [String: String]
            var details: [DetailsCase]
            var edits: [Case]
            var isDark: [[String: String]]
        }
        let golden = Golden(
            note: "Generated by tools/MakeEditorGolden.swift from Renderooo/MermaidSourceEditor.swift. `source` names a key of `sources`.",
            sources: files, details: details, edits: edits, isDark: isDark
        )
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        try FileManager.default.createDirectory(atPath: "porting/golden", withIntermediateDirectories: true)
        try encoder.encode(golden).write(to: URL(fileURLWithPath: "porting/golden/mermaid-editor.json"))
        print("porting/golden/mermaid-editor.json: \(details.count) details, \(edits.count) edits")
    }
}
